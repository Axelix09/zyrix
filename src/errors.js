class ZyrixError extends Error {
  constructor(message, { kind = 'unknown', code, errorCode, details, cause } = {}) {
    super(message, cause ? { cause } : undefined)
    this.name = 'ZyrixError'
    this.kind = kind
    // errorCode: identificador estable en inglés (p. ej. 'MEDIA_URL_BLOCKED'); no cambia
    // aunque cambie el texto del mensaje. code: código que envía WhatsApp, cuando hay uno.
    if (errorCode !== undefined) this.errorCode = errorCode
    if (code !== undefined) this.code = code
    if (details !== undefined) this.details = details
  }

  get retryable() {
    return this.kind === ErrorKind.TIMEOUT || this.kind === ErrorKind.CLOSED || this.kind === ErrorKind.NOT_READY
  }

  toJSON() {
    return { name: this.name, kind: this.kind, errorCode: this.errorCode, code: this.code, message: this.message, retryable: this.retryable }
  }
}

const isZyrixError = (value, kind) => value instanceof ZyrixError && (kind === undefined || value.kind === kind)

export { ZyrixError, ErrorKind, ErrorCode, isZyrixError }
