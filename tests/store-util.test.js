const event = (id, jid, fromMe = false, at = 1) => ({ key: { id, remoteJid: jid, fromMe }, message: { conversation: id }, messageTimestamp: at })

test('store: guarda mensajes/chats/contactos/grupos/presencias con límites', () => {
  const socket = new EventEmitter()
  const store = createStore(socket, { maxMessagesPerChat: 2, maxChats: 2, maxContacts: 2 })
  for (const id of ['1', '2', '3']) socket.emit('messages.upsert', event(id, 'a'))
  assert.deepEqual(store.getMessages('a').map((e) => e.key.id), ['2', '3'])
  assert.equal(store.loadMessage('a', '3').key.remoteJid, 'a')
  assert.equal(store.getMessage({ remoteJid: 'a', id: '3' }).conversation, '3')
  assert.equal(store.getMessage(null), undefined)
  assert.deepEqual(store.getMessages('nope'), [])
  socket.emit('messages.upsert', event('x', 'b'))
  socket.emit('messages.upsert', event('y', 'c'))
  assert.equal(store.getChats().length, 2)
  assert.equal(store.getChat('a'), undefined)
  socket.emit('messages.upsert', {})
  assert.equal(store.getChats().length, 2)

  socket.emit('chats.update', { id: 'a', unread: 5 })
  socket.emit('chats.update', null)
  assert.equal(store.getChat('a').unread, 5)
  socket.emit('contacts.upsert', { id: 'c1', name: 'Ana' })
  socket.emit('contacts.upsert', { id: 'c2' })
  socket.emit('contacts.upsert', { id: 'c3' })
  socket.emit('contacts.upsert', null)
  assert.equal(store.getContacts().length, 2)
  assert.equal(store.getContact('c3').id, 'c3')

  socket.emit('groups.update', [{ id: 'g', participants: [{ id: '1' }, { id: '2' }] }])
  socket.emit('groups.update', { id: 'g2', participants: [] })
  socket.emit('groups.update', [null])
  assert.equal(store.getGroups().length, 2)
  assert.equal(store.getGroup('g').id, 'g')

  socket.emit('group-participants.update', { id: 'g', action: 'add', participantsInfo: [{ id: '3' }, { id: '1' }] })
  assert.equal(store.getGroup('g').participants.length, 3)
  socket.emit('group-participants.update', { id: 'g', action: 'promote', participantsInfo: [{ id: '3' }] })
  assert.equal(store.getGroup('g').participants.find((p) => p.id === '3').isAdmin, true)
  socket.emit('group-participants.update', { id: 'g', action: 'demote', participantsInfo: [{ id: '3' }] })
  assert.equal(store.getGroup('g').participants.find((p) => p.id === '3').isAdmin, false)
  socket.emit('group-participants.update', { id: 'g', action: 'remove', participantsInfo: [{ id: '3' }] })
  assert.equal(store.getGroup('g').participants.length, 2)
  socket.emit('group-participants.update', { id: 'g', action: 'leave', participantsInfo: [{ id: '1' }] })
  assert.equal(store.getGroup('g').participants.length, 1)
  socket.emit('group-participants.update', { id: 'nope', action: 'add', participantsInfo: [] })
  socket.emit('group-participants.update', { id: 'g2', action: 'add', participantsInfo: [] })

  socket.emit('presence.update', { id: 'a', presences: { a: { lastKnownPresence: 'available' } } })
  assert.deepEqual(store.getPresence('a').a.lastKnownPresence, 'available')
  socket.emit('presence.update', { id: 'a', presences: { b: { lastKnownPresence: 'composing' } } })
  assert.equal(store.getPresence('a').b.lastKnownPresence, 'composing')
  assert.equal(createStore.length, 1)
  assert.throws(() => createStore(null), TypeError)
})

test('store: toJSON/fromJSON respeta límites y rechaza datos inválidos', () => {
  const socket = new EventEmitter()
  const store = createStore(socket, { maxMessagesPerChat: 1, maxChats: 1, maxContacts: 1 })
  socket.emit('messages.upsert', event('1', 'a'))
  socket.emit('messages.upsert', event('2', 'a'))
  const data = store.toJSON()
  assert.equal(data.messages.length, 1)
  store.fromJSON(data)
  assert.equal(store.getMessages('a')[0].key.id, '2')
  assert.equal(store.fromJSON({ version: 1 }), store)
  assert.throws(() => store.fromJSON(null), TypeError)
  assert.throws(() => store.fromJSON({ version: 2 }), TypeError)
  assert.throws(() => store.fromJSON({ messages: 'x' }), TypeError)
  assert.throws(() => store.fromJSON({ messages: [['a']] }), TypeError)
  assert.throws(() => store.fromJSON({ messages: [['', []]] }), TypeError)
  assert.throws(() => store.fromJSON({ messages: [['a', 'x']] }), TypeError)
  assert.throws(() => store.fromJSON({ messages: [['a', [{}]]] }), TypeError)
  assert.throws(() => store.fromJSON({ messages: [['a', [{ key: {} }]]] }), TypeError)
  assert.throws(() => store.fromJSON({ chats: [{}] }), TypeError)
  assert.throws(() => store.fromJSON({ contacts: 'x' }), TypeError)
  assert.throws(() => store.fromJSON({ groups: [{}] }), TypeError)
})

test('store: writeToFile serializa, rota el temporal y readFromFile restaura', async (t) => {
  const dir = await mkdtemp(path.join(tmpdir(), 'zyrix-store-'))
  t.after(() => rm(dir, { recursive: true, force: true }))
  const socket = new EventEmitter()
  const store = createStore(socket)
  socket.emit('messages.upsert', event('1', 'a'))
  socket.emit('contacts.upsert', { id: 'c', name: 'Ana', avatar: Buffer.from('x') })
  const file = path.join(dir, 'store.json')
  await Promise.all([store.writeToFile(file), store.writeToFile(file)])
  const files = await readdir(dir)
  assert.deepEqual(files, ['store.json'])
  const raw = JSON.parse(await readFile(file, 'utf8'), jsonReviver)
  assert.deepEqual(raw.contacts[0].avatar, Buffer.from('x'))

  const restored = createStore(new EventEmitter())
  restored.readFromFile(file)
  assert.equal(restored.getMessages('a').length, 1)
  assert.equal(restored.getContact('c').name, 'Ana')
  assert.equal(restored.readFromFile(path.join(dir, 'missing.json')), restored)

  await writeFile(path.join(dir, 'bad.json'), '{')
  assert.throws(() => restored.readFromFile(path.join(dir, 'bad.json')))
  const failure = createStore(new EventEmitter()).writeToFile(path.join(dir, 'no-dir', 'x.json'))
  await assert.rejects(failure)
  const left = (await readdir(dir)).filter((f) => f.endsWith('.tmp'))
  assert.deepEqual(left, [])

  store.unbind()
  socket.emit('messages.upsert', event('2', 'a'))
  assert.equal(store.getMessages('a').length, 1)
})

test('store: makeInMemoryStore exige bind y permite reemplazar el socket', () => {
  const store = makeInMemoryStore()
  assert.throws(() => store.getChats(), { errorCode: 'STORE_NOT_BOUND' })
  const first = new EventEmitter()
  assert.equal(store.bind(first), store)
  first.emit('messages.upsert', event('1', 'a'))
  assert.equal(store.getMessages('a').length, 1)
  const second = new EventEmitter()
  store.bind(second)
  assert.equal(store.getMessages('a').length, 0)
  first.emit('messages.upsert', event('2', 'a'))
  assert.equal(store.getMessages('a').length, 0)
  store.unbind()
  assert.throws(() => store.getChats(), { errorCode: 'STORE_NOT_BOUND' })
})

test('util: enteros, ids, padding y TTL', async () => {
  assert.deepEqual(be(0x010203, 4), Buffer.from([0, 1, 2, 3]))
  assert.equal(readBE(Buffer.from([1, 2])), 258)
  assert.match(genId(), /^3EB0[0-9A-F]{18}$/)
  const padded = pad(Buffer.from('hola'))
  assert.deepEqual(unpad(padded), Buffer.from('hola'))
  assert.equal(num({ toNumber: () => 7 }), 7)
  assert.equal(num(5), 5)
  assert.equal(num(undefined), 0)
  const cache = new TTLCache({ max: 2, ttl: 5 })
  cache.set('a', 1).set('b', 2).set('c', 3)
  assert.equal(cache.size, 2)
  assert.equal(cache.has('a'), false)
  assert.equal(cache.get('b'), 2)
  cache.set('d', 4)
  assert.equal(cache.get('c'), undefined)
  cache.clear()
  assert.equal(cache.size, 0)
  await sleep(1)
})

test('util: toBuffer acepta buffer, data URL, base64, archivo, URL y stream', async (t) => {
  const dir = await mkdtemp(path.join(tmpdir(), 'zyrix-buffer-'))
  t.after(() => rm(dir, { recursive: true, force: true }))
  const file = path.join(dir, 'a.bin')
  await writeFile(file, 'archivo')
  assert.deepEqual(await toBuffer(Buffer.from('x')), Buffer.from('x'))
  assert.deepEqual(await toBuffer(new Uint8Array([1, 2])), Buffer.from([1, 2]))
  assert.deepEqual(await toBuffer('data:text/plain;base64,aG9sYQ=='), Buffer.from('hola'))
  assert.deepEqual(await toBuffer('data:text/plain,hola%20mundo'), Buffer.from('hola mundo'))
  assert.deepEqual(await toBuffer({ data: Buffer.from('base64').toString('base64') }), Buffer.from('base64'))
  assert.deepEqual(await toBuffer(file), Buffer.from('archivo'))
  assert.deepEqual(await toBuffer({ path: file }), Buffer.from('archivo'))
  assert.deepEqual(await toBuffer({ url: file }), Buffer.from('archivo'))
  assert.deepEqual(await toBuffer({ url: 'data:text/plain,abc' }), Buffer.from('abc'))
  assert.deepEqual(await toBuffer({ stream: Readable.from([Buffer.from('a'), Buffer.from('b')]) }), Buffer.from('ab'))
  await assert.rejects(toBuffer(Buffer.alloc(3), 2), RangeError)
  await assert.rejects(toBuffer('data:text/plain,abc', 2), RangeError)
  await assert.rejects(toBuffer({ data: 'YWJj' }, 2), RangeError)
  await assert.rejects(toBuffer({ path: file }, 2), RangeError)
  await assert.rejects(toBuffer({ stream: Readable.from([Buffer.from('abc')]) }, 2), RangeError)
  await assert.rejects(toBuffer(42), TypeError)
  await assert.rejects(toBuffer({ url: 'data:text/plain;base64' }), /ENOENT/)
})

test('util: sniffMimeType reconoce formatos y respeta el fallback', () => {
  assert.equal(sniffMimeType(Buffer.from([0xff, 0xd8, 0xff, 0])), 'image/jpeg')
  assert.equal(sniffMimeType(Buffer.from([0x89, 0x50, 0x4e, 0x47])), 'image/png')
  assert.equal(sniffMimeType(Buffer.from('GIF8')), 'image/gif')
  const webp = Buffer.concat([Buffer.from('RIFF'), Buffer.alloc(4), Buffer.from('WEBP'), Buffer.alloc(1)])
  assert.equal(sniffMimeType(webp), 'image/webp')
  const mp4 = Buffer.concat([Buffer.alloc(4), Buffer.from('ftypmp42'), Buffer.alloc(1)])
  assert.equal(sniffMimeType(mp4), 'video/mp4')
  const qt = Buffer.concat([Buffer.alloc(4), Buffer.from('ftypqt  '), Buffer.alloc(1)])
  assert.equal(sniffMimeType(qt), 'video/quicktime')
  assert.equal(sniffMimeType(Buffer.from('%PDF-1.4')), 'application/pdf')
  assert.equal(sniffMimeType(Buffer.from('ID3xxxxxxx')), 'audio/mpeg')
  assert.equal(sniffMimeType(Buffer.from([0x4f, 0x67, 0x67, 0x53])), 'audio/ogg')
  assert.equal(sniffMimeType(Buffer.from([0xff, 0xe0, 0, 0])), 'audio/mpeg')
  assert.equal(sniffMimeType(Buffer.alloc(1), 'x/y'), 'x/y')
  assert.equal(sniffMimeType(null), undefined)
})

test('util: redirectHeaders y clasificación de IPs', () => {
  const headers = { Host: 'a', Authorization: 'b', Cookie: 'c', 'User-Agent': 'ua', Accept: '*/*', 'X-Custom': 'x' }
  assert.deepEqual(redirectHeaders(headers, true), headers)
  assert.deepEqual(redirectHeaders(headers, false), { 'User-Agent': 'ua', Accept: '*/*' })
  assert.equal(isPublicAddress('8.8.8.8'), true)
  assert.equal(isPublicAddress('127.0.0.1'), false)
  assert.equal(isPublicAddress('10.0.0.1'), false)
  assert.equal(isPublicAddress('192.168.1.1'), false)
  assert.equal(isPublicAddress('100.64.0.1'), false)
  assert.equal(isPublicAddress('::1'), false)
  assert.equal(isPublicAddress('fd00::1'), false)
  assert.equal(isPublicAddress('2001:4860:4860::8888'), true)
  assert.equal(isPublicAddress('::ffff:8.8.8.8'), true)
  assert.equal(isPublicAddress('no-ip'), false)
})

test('util: assertPublicMediaUrl y publicOnlyLookup bloquean hosts locales/privados', async () => {
  assert.equal((await assertPublicMediaUrl('https://example.com/x')).href, 'https://example.com/x')
  await assert.rejects(assertPublicMediaUrl('http://localhost/x'), { errorCode: 'MEDIA_URL_BLOCKED' })
  await assert.rejects(assertPublicMediaUrl('http://127.0.0.1/x'), { errorCode: 'MEDIA_URL_BLOCKED' })
  await assert.rejects(assertPublicMediaUrl('http://user:pass@example.com/x'), { errorCode: 'MEDIA_URL_BLOCKED' })
  await assert.rejects(assertPublicMediaUrl('http://example.com:8080/x'), { errorCode: 'MEDIA_URL_BLOCKED' })
  await assert.rejects(assertPublicMediaUrl('ftp://example.com/x'))
  const lookupError = await new Promise((resolve) => publicOnlyLookup('localhost', { all: true }, (err) => resolve(err)))
  assert.equal(lookupError.errorCode, 'MEDIA_URL_BLOCKED')
})

test('util: json replacer/reviver y logger', () => {
  const json = JSON.stringify({ b: Buffer.from('x'), u: new Uint8Array([1]) }, jsonReplacer)
  assert.deepEqual(JSON.parse(json, jsonReviver), { b: Buffer.from('x'), u: Buffer.from([1]) })
  assert.deepEqual(jsonReviver('k', { type: 'Buffer', data: [1, 2] }), Buffer.from([1, 2]))
  assert.equal(jsonReviver('k', 1), 1)
  const calls = []
  const logger = makeLogger({ log: (...a) => calls.push(a), error: (...a) => calls.push(['error', ...a]) })
  logger.trace('t')
  logger.debug('d')
  logger.error('e')
  logger.info('i')
  const silent = makeLogger()
  silent.error('nada')
  assert.equal(calls.length, 4)
})
